def test_dataset_lines_are_wellformed_and_local(built_dataset: Path) -> None:
    lines = (built_dataset / "dataset.jsonl").read_text(encoding="utf-8").splitlines()
    kinds = {}
    for line in lines:
        payload = json.loads(line)
        kinds[payload["kind"]] = kinds.get(payload["kind"], 0) + 1
    assert set(kinds) == {"song", "event", "pair"}
    pair_lines = [json.loads(line) for line in lines if json.loads(line)["kind"] == "pair"]
    for pair in pair_lines:
        assert pair["preferred_onset_id"] != pair["other_onset_id"]
        assert pair["support_gap"] >= 0.34


