def _run_builder(corpus: Path, output: Path, *extra: str) -> int:
    import subprocess

    completed = subprocess.run(
        [sys.executable, str(SCRIPT), "--corpus", str(corpus), "--output", str(output), *extra],
        cwd=str(REPO_ROOT), capture_output=True, text=True,
    )
    return completed.returncode


