def test_builder_refuses_consumed_artifact_rebuild(tmp_path_factory: pytest.TempPathFactory,
                                                   monkeypatch: pytest.MonkeyPatch) -> None:
    import beatscope.chart_labels as cl
    from scripts.build_event_ranking_dataset import build_dataset

    root = tmp_path_factory.mktemp("denylist-corpus")
    registry = build_synthetic_corpus(root)
    first_out = tmp_path_factory.mktemp("denylist-first")
    manifest, _ = build_dataset(registry, first_out)
    assert manifest["totals"]["song_count"] == 3

    dataset_sha = cl.sha256_text((first_out / "dataset.jsonl").read_text(encoding="utf-8"))
    monkeypatch.setattr(cl, "CONSUMED_V2_ARTIFACTS",
                        cl.CONSUMED_V2_ARTIFACTS + (dataset_sha,))
    second_out = tmp_path_factory.mktemp("denylist-second")
    with pytest.raises(SystemExit) as exit_info:
        build_dataset(registry, second_out)
    assert exit_info.value.code == 1
    assert not (second_out / "dataset.jsonl").exists()
