def test_same_audio_never_crosses_splits(built_dataset: Path) -> None:
    manifest = json.loads((built_dataset / "training-manifest.json").read_text(encoding="utf-8"))
    by_sha: dict[str, str] = {}
    for song in manifest["songs"]:
        if song["audio_sha256"] in by_sha:
            pytest.fail("one audio sha appeared twice in the manifest")
        by_sha[song["audio_sha256"]] = song["split"]
    by_fingerprint: dict[str, str] = {}
    for song in manifest["songs"]:
        seen = by_fingerprint.setdefault(song["fingerprint"], song["split"])
        assert seen == song["split"], "fingerprint cluster leaked across splits"


