def test_event_lines_carry_evidence_but_no_chart_time(built_dataset: Path) -> None:
    lines = [json.loads(line) for line in
             (built_dataset / "dataset.jsonl").read_text(encoding="utf-8").splitlines()]
    events = [payload for payload in lines if payload["kind"] == "event"]
    assert events
    for event in events:
        assert event["evidence"]["onset_id"] == event["onset_id"]
        assert "markers_seconds" not in json.dumps(event)
    # Support rates come from the survival pattern: quarters 1.0, offbeats 1/3.
    rates = {round(event["support_rate"], 6) for event in events}
    assert 1.0 in rates
    assert any(abs(rate - 1 / 3) < 1e-3 for rate in rates)


