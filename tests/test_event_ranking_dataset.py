def test_explicit_source_partition_is_preserved_end_to_end(
        synthetic_corpus: Path, tmp_path_factory: pytest.TempPathFactory) -> None:
    partition_root = tmp_path_factory.mktemp("partitioned-ranking-corpus")
    development = partition_root / "development"
    holdout = partition_root / "holdout"
    for name in ("song-a", "song-b"):
        shutil.copytree(synthetic_corpus.parent / name, development / name)
    shutil.copytree(synthetic_corpus.parent / "song-c", holdout / "song-c")
    registry = {
        "schema": "beatscope-ranking-corpus-local-1",
        "sources": [
            {
                "id": "development",
                "root": str(development),
                "format": "stepmania",
                "license": "synthetic-original",
                "permission_note": "Generated test material",
                "source_revision": "rev-development",
                "partition": "development",
            },
            {
                "id": "independent-holdout",
                "root": str(holdout),
                "format": "stepmania",
                "license": "synthetic-original",
                "permission_note": "Generated test material reserved as holdout",
                "source_revision": "rev-holdout",
                "partition": "test",
            },
        ],
    }
    registry_path = partition_root / "corpus.local.json"
    registry_path.write_text(
        json.dumps(registry, indent=2) + "\n", encoding="utf-8", newline="\n")
