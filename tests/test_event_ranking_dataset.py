SCRIPT = REPO_ROOT / "scripts" / "build_event_ranking_dataset.py"
FORBIDDEN_ROLE_WORDS = ("foreground", "background")

SONG_BPMS = {"song-a": 120.0, "song-b": 100.0, "song-c": 110.0}


def _marker_row(lane: int) -> str:
    return "0" * lane + "1" + "0" * (3 - lane)


def _chart_text(beats: list[float], bpm: float, difficulty: str, meter: int) -> str:
    measures: dict[int, set[float]] = {}
    for beat in beats:
        measure = int(beat // 4)
        within = beat - measure * 4
        measures.setdefault(measure, set()).add(round(within, 6))
    blocks = []
    for measure in range(max(measures) + 1):
        markers = measures.get(measure, set())
        row_count = 8 if any(abs(within % 1.0) > 1e-9 for within in markers) else 4
        lines = []
        for row_index in range(row_count):
            within = 4.0 * row_index / row_count
            if within in markers:
                lines.append(_marker_row(row_index % 4))
            else:
                lines.append("0000")
        blocks.append("\n".join(lines))
    return (
        "#TITLE:Synthetic Song;\n"
        f"#MUSIC:audio.wav;\n"
        "#OFFSET:0.000000;\n"
        f"#BPMS:0={bpm:.3f};\n"
        "#NOTES:\n"
        f":dance-single:{difficulty}:{meter}:\n"
        + ",\n".join(blocks)
        + ";\n"
    )


def _song_layout() -> tuple[list[float], list[float], list[float]]:
    """Charts live in the beat domain; audio clicks land at beat * seconds-per-beat."""
    quarters = [float(index) for index in range(16)]
    offbeats = [float(index) + 0.5 for index in (0, 4, 8, 12)]
    all_beats = sorted(quarters + offbeats)
    return quarters, offbeats, all_beats


def _write_wav(path: Path, click_beats: list[float], bpm: float) -> None:
    import wave

    from tests.fixtures.generate_audio import add_click, float_to_pcm16

    seconds_per_beat = 60.0 / bpm
    sr = 22050
    click_times = [round(beat * seconds_per_beat, 6) for beat in click_beats]
    duration = click_times[-1] + seconds_per_beat + 0.5
    signal = np.zeros(int(round(duration * sr)))
    for click in click_times:
        add_click(signal, sr, click, 1000.0, 0.7)
    pcm = float_to_pcm16(signal)
    with wave.open(str(path), "wb") as handle:
        handle.setnchannels(1)
        handle.setsampwidth(2)
        handle.setframerate(sr)
        handle.writeframes(pcm.tobytes())


def build_synthetic_corpus(root: Path) -> Path:
    """Three original songs, three difficulties each, plus the corpus registry."""
    for name, bpm in SONG_BPMS.items():
        song_dir = root / name
        song_dir.mkdir(parents=True, exist_ok=True)
        quarters, offbeats, all_beats = _song_layout()
        _write_wav(song_dir / "audio.wav", all_beats, bpm)
        easy = [quarters[index] for index in (0, 4, 8, 12)]
        normal = list(quarters)
        hard = sorted(quarters + offbeats)
        (song_dir / "easy.sm").write_text(
            _chart_text(easy, bpm, "Easy", 1), encoding="utf-8", newline="\n")
        (song_dir / "normal.sm").write_text(
            _chart_text(normal, bpm, "Normal", 5), encoding="utf-8", newline="\n")
        (song_dir / "hard.sm").write_text(
            _chart_text(hard, bpm, "Hard", 9), encoding="utf-8", newline="\n")
    registry = {
        "schema": "beatscope-ranking-corpus-local-1",
        "sources": [
            {
                "id": "synthetic-original-pack",
                "root": str(root),
                "format": "stepmania",
                "license": "synthetic-original",
                "permission_note": "Generated by the test suite; no third-party content",
            }
        ],
    }
    registry_path = root / "corpus.local.json"
    registry_path.write_text(json.dumps(registry, indent=2) + "\n", encoding="utf-8", newline="\n")
    return registry_path


