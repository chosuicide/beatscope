def build_two_source_development_corpus(root: Path) -> Path:
    """Two independent development sources, both partitioned and revised."""
    packs = {"pack-one": ("song-a",), "pack-two": ("song-b", "song-c")}
    sources = []
    for pack_id, songs in packs.items():
        pack_dir = root / pack_id
        pack_dir.mkdir(parents=True, exist_ok=True)
        for name in songs:
            bpm = SONG_BPMS[name]
            song_dir = pack_dir / name
            song_dir.mkdir(parents=True, exist_ok=True)
            quarters, offbeats, all_beats = _song_layout()
            _write_wav(song_dir / "audio.wav", all_beats, bpm)
            easy = [quarters[index] for index in (0, 4, 8, 12)]
            normal = list(quarters)
            hard = sorted(quarters + offbeats)
            (song_dir / "easy.sm").write_text(
                _chart_text(easy, bpm, "Easy", 1), encoding="utf-8", newline="\n")
            (song_dir / "normal.sm").write_text(
                _chart_text(normal, bpm, "Normal", 5), encoding="utf-8", newline="\n")
            (song_dir / "hard.sm").write_text(
                _chart_text(hard, bpm, "Hard", 9), encoding="utf-8", newline="\n")
        sources.append({
            "id": pack_id,
            "root": str(pack_dir),
            "format": "stepmania",
            "license": "synthetic-original",
            "permission_note": f"Generated by the test suite for {pack_id}",
            "source_revision": f"rev-{pack_id}",
            "partition": "development",
        })
    registry_path = root / "development-corpus.local.json"
    registry_path.write_text(json.dumps({
        "schema": "beatscope-ranking-corpus-local-1", "sources": sources,
    }, indent=2) + "\n", encoding="utf-8", newline="\n")
    return registry_path


